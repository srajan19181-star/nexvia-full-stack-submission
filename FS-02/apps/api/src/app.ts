import express from "express";
import cookieParser from "cookie-parser";
import cors from "cors";
import helmet from "helmet";
import { rateLimit } from "express-rate-limit";
import pinoHttp from "pino-http";
import { prisma } from "@aureva/database";
import { allowedOrigins, env } from "./config";
import { csrfProtection } from "./auth";
import { errorHandler, ok } from "./http";
import { authRoutes } from "./routes/auth-routes";
import { catalogRoutes } from "./routes/catalog-routes";
import { customerRoutes } from "./routes/customer-routes";
import { vendorRoutes } from "./routes/vendor-routes";
import { adminRoutes } from "./routes/admin-routes";
import { checkoutRoutes, handleStripeWebhook } from "./routes/checkout-routes";
import { customerOperationsRoutes } from "./routes/customer-operations-routes";
import { vendorOperationsRoutes } from "./routes/vendor-operations-routes";
import { adminOperationsRoutes } from "./routes/admin-operations-routes";
import { userRoutes } from "./routes/user-routes";
import { searchProducts, suggestProducts } from "./search";
import { handleCarrierWebhook } from "./carrier";
import { publicRoutes } from "./routes/public-routes";
import { openapiDocument } from "./openapi";
import { cacheReady } from "./cache";

export function createApp() {
  const app = express(); app.disable("x-powered-by");
  if (env.TRUST_PROXY_HOPS > 0) app.set("trust proxy", env.TRUST_PROXY_HOPS);
  app.use(pinoHttp({ redact: ["req.headers.cookie", "req.headers.authorization", "req.body.password", "req.body.token"] }));
  app.use(helmet({ contentSecurityPolicy: false }));
  app.use(cors({ origin(origin, callback) { callback(null, !origin || allowedOrigins.includes(origin)); }, credentials: true }));
  app.post("/api/v1/webhooks/stripe", express.raw({ type: "application/json", limit: "1mb" }), async (request, response, next) => { try { ok(response, await handleStripeWebhook(request.body as Buffer, request.get("stripe-signature"))); } catch (error) { next(error); } });
  app.post("/api/v1/webhooks/carrier", express.raw({ type: "application/json", limit: "256kb" }), async (request, response, next) => { try { ok(response, await handleCarrierWebhook(request.body as Buffer, request.get("x-aureva-signature"))); } catch (error) { next(error); } });
  app.use(express.json({ limit: "1mb" }), cookieParser());
  app.use("/api/v1", rateLimit({ windowMs: 15 * 60_000, limit: 600, standardHeaders: "draft-8", legacyHeaders: false }));
  app.use("/api/v1/auth/login", rateLimit({ windowMs: 15 * 60_000, limit: 10, standardHeaders: "draft-8", legacyHeaders: false }));
  app.use("/api/v1/auth/forgot-password", rateLimit({ windowMs: 60 * 60_000, limit: 5, standardHeaders: "draft-8", legacyHeaders: false }));
  app.use("/api/v1/auth", rateLimit({ windowMs: 15 * 60_000, limit: 50, standardHeaders: "draft-8", legacyHeaders: false }), authRoutes);
  app.use("/api/v1/newsletter", rateLimit({ windowMs: 15 * 60_000, limit: 100, standardHeaders: "draft-8", legacyHeaders: false }));
  app.use("/api/v1", publicRoutes);
  app.use(csrfProtection);
  app.get("/health", (_request, response) => ok(response, { status: "healthy", timestamp: new Date().toISOString() }));
  app.get("/ready", async (_request, response, next) => { try { await prisma.$queryRaw`SELECT 1`; if (!await cacheReady()) throw new Error("Redis is not ready"); ok(response, { status: "ready", dependencies: { postgres: "ready", redis: "ready" } }); } catch (error) { next(error); } });
  app.get("/api/v1/openapi.json", (_request, response) => response.json(openapiDocument));
  app.get("/api/v1/search", async (request, response, next) => { try { const query = typeof request.query.q === "string" ? request.query.q.trim() : ""; if (query.length < 2) return ok(response, { source: "none", products: [] }); return ok(response, await searchProducts(query)); } catch (error) { next(error); } });
  app.get("/api/v1/search/suggestions",async(request,response,next)=>{try{const query=typeof request.query.q==="string"?request.query.q.trim():"";return ok(response,query.length<2?{products:[],vendors:[],categories:[]}:await suggestProducts(query));}catch(error){next(error);}});
  app.use("/api/v1", catalogRoutes);
  app.use("/api/v1/vendors", vendorRoutes);
  app.use("/api/v1/vendors", vendorOperationsRoutes);
  app.use("/api/v1/admin", adminRoutes);
  app.use("/api/v1/admin", adminOperationsRoutes);
  app.use("/api/v1", customerRoutes);
  app.use("/api/v1", customerOperationsRoutes);
  app.use("/api/v1", checkoutRoutes);
  app.use("/api/v1", userRoutes);
  app.use((_request, response) => response.status(404).json({ success: false, error: { code: "NOT_FOUND", message: "Route not found" } }));
  app.use(errorHandler);
  return app;
}
